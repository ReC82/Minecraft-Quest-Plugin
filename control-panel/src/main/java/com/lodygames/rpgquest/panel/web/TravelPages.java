    static String places(Ctx ctx, Survey s, PlaceQuery q) {
        StringBuilder sb = new StringBuilder();
        sb.append(placeSearch(ctx, s, q));
        List<Place> shown = filterPlaces(s, q);
        if (s.places().isEmpty()) {
            return sb.append(Ui.empty("travel", "Aucun lieu pour l'instant. Un lieu apparaît quand un joueur "
                    + "découvre une nouvelle zone.")).toString();
        }
        if (shown.isEmpty()) {
            return sb.append(Ui.empty("search", "Aucun lieu ne correspond à cette recherche.")).toString();
        }
        int pageCount = Math.max(1, (shown.size() + PAGE_SIZE - 1) / PAGE_SIZE);
        int page = Math.max(1, Math.min(q.page(), pageCount));
        List<Place> slice = shown.subList((page - 1) * PAGE_SIZE, Math.min(shown.size(), page * PAGE_SIZE));
        sb.append("<p class=\"count-note\">").append(shown.size() == s.places().size()
                ? count(shown.size(), "lieu", "lieux")
                : shown.size() + " sur " + count(s.places().size(), "lieu", "lieux")).append("</p>");
        sb.append("<ul class=\"qc-list tv-list\">");
        for (Place p : slice) {
            sb.append(placeRow(ctx, s, p));
        }
        sb.append("</ul>");
        sb.append(pager(page, pageCount, n -> placesUrl(ctx, q, n)));
        sb.append(seeAlso(ctx));
        return sb.toString();
    }

