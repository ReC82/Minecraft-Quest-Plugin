    static Survey parse(Map<String, Object> d) {
        List<Place> places = new ArrayList<>();
        for (Object o : list(d.get("waypoints"))) {
            Map<String, Object> m = map(o);
            places.add(new Place(str(m.get("id")), str(m.get("displayName")), str(m.get("world")),
                    str(m.get("biomeKey")), str(m.get("biomeInstance")), integer(m.get("x")), integer(m.get("y")),
                    integer(m.get("z")), Boolean.TRUE.equals(m.get("active")), str(m.get("pairedBeaconId")),
                    str(m.get("createdAt")), str(m.get("modelVersion"))));
        }
        List<Beacon> beacons = new ArrayList<>();
        for (Object o : list(d.get("beacons"))) {
            Map<String, Object> m = map(o);
            beacons.add(new Beacon(str(m.get("id")), str(m.get("world")), integer(m.get("x")), integer(m.get("y")),
                    integer(m.get("z")), Boolean.TRUE.equals(m.get("active")),
                    Boolean.TRUE.equals(m.get("autoGenerated")), str(m.get("biomeInstance")),
                    str(m.get("pairedWaypointId")), str(m.get("createdAt"))));
        }
        List<Missing> missing = new ArrayList<>();
        for (Object o : list(d.get("unpairedHubInstances"))) {
            Map<String, Object> m = map(o);
            missing.add(new Missing(str(m.get("waypointId")), str(m.get("biomeKey")), str(m.get("biomeInstance")),
                    integer(m.get("x")), integer(m.get("z")), integer(m.get("attempts")),
                    Boolean.TRUE.equals(m.get("inProgress")),
                    m.get("nearestBeaconDistance") instanceof Number n ? n.intValue() : -1,
                    m.get("nextRetryEpochMs") instanceof Number n ? n.longValue() : null));
        }
        return new Survey(List.copyOf(places), List.copyOf(beacons), List.copyOf(missing),
                TravelNetworkDiagnostic.from(d));
    }

