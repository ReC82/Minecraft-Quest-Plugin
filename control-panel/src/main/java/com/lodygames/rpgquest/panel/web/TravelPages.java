    /** {@code /travel?agent=…[&tab=…][&focus=…]}. */
    static String url(Ctx ctx, Tab tab, String focus) {
        StringBuilder sb = new StringBuilder(PAGE).append("?agent=").append(enc(ctx.agentId()));
        if (tab != Tab.PLACES) {
            sb.append("&tab=").append(tab.wire);
        }
        if (!focus.isEmpty()) {
            sb.append("&focus=").append(enc(focus));
        }
        return sb.toString();
    }

    private static String placesUrl(Ctx ctx, PlaceQuery q, int page) {
        StringBuilder sb = new StringBuilder(url(ctx, Tab.PLACES, ""));
        if (!q.search().isEmpty()) {
            sb.append("&q=").append(enc(q.search()));
        }
        if (q.kind() != Kind.ALL) {
            sb.append("&kind=").append(q.kind().wire);
        }
        if (q.recentFirst()) {
            sb.append("&sort=recent");
        }
        return sb.append("&p=").append(page).toString();
    }

    private static String pager(int page, int pageCount, java.util.function.IntFunction<String> href) {
        if (pageCount <= 1) {
            return "";
        }
        StringBuilder sb = new StringBuilder("<nav class=\"pager tv-pager\" aria-label=\"Pages\">");
        if (page > 1) {
            sb.append("<a class=\"btn secondary sm\" href=\"").append(Http.esc(href.apply(page - 1)))
                    .append("\">Précédent</a>");
        }
        sb.append("<span class=\"muted\">Page ").append(page).append(" sur ").append(pageCount).append("</span>");
        if (page < pageCount) {
            sb.append("<a class=\"btn secondary sm\" href=\"").append(Http.esc(href.apply(page + 1)))
                    .append("\">Suivant</a>");
        }
        return sb.append("</nav>").toString();
    }

    /** Même règle que le reste du panel : une case seulement pour une action réellement sensible. */
    private static String consent(String type, String checkboxText) {
        boolean sensitive = AgentActionCatalog.spec(type).map(AgentActionCatalog.Spec::sensitive).orElse(true);
        return sensitive
                ? "<label class=\"inline confirm\"><input type=\"checkbox\" name=\"confirm\" value=\"true\" required> "
                        + Http.esc(checkboxText) + "</label>"
                : hidden("confirm", "true");
    }

