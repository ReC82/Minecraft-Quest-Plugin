    private static String howToGo(Survey s, Place p) {
        return switch (s.kindOf(p.world())) {
            case HUB -> p.hasBeacon()
                    ? "Une borne du Village mène à ce lieu : les joueurs qui l'ont découvert peuvent y voyager."
                    : "Ce lieu n'a pas encore de borne. Elle sera posée toute seule la prochaine fois qu'un joueur "
                            + "passera par là (voir l'onglet « À vérifier »).";
            case WILD -> "Dans le Monde sauvage, on voyage avec les Waystones que les joueurs découvrent, pas avec des "
                    + "bornes. C'est normal que ce lieu n'en ait pas.";
            case OTHER, ALL -> "Ce lieu n'est ni dans le Village ni dans le Monde sauvage : aucune borne n'y est posée.";
        };
    }

    private static String renameCard(Ctx ctx, Survey s, Place p) {
        // Index des noms des AUTRES lieux pour l'avertissement en direct de panel.js (data-name-taken,
        // composant #125) ; la clé suit sa comparaison (minuscules, espaces réduits).
        Map<String, Object> taken = new java.util.LinkedHashMap<>();
        for (Place other : s.places()) {
            if (!other.id().equals(p.id()) && !other.name().isBlank()) {
                String key = other.name().replaceAll("\\s+", " ").trim().toLowerCase(Locale.ROOT);
                taken.put(key, List.of(other.name() + " (" + worldName(other.world()) + ")"));
            }
        }
        StringBuilder sb = new StringBuilder("<section class=\"qc-card tv-rename\" id=\"renommer\"><h2>")
                .append(Icons.icon("edit")).append("Renommer ce lieu</h2>");
        sb.append("<form method=\"post\" action=\"/agents/action\" class=\"actform tv-rename-form\">");
        sb.append(hidden("_csrf", ctx.csrf())).append(hidden("agent", ctx.agentId()))
                .append(hidden("type", "waypoint.rename")).append(hidden("return", PAGE))
                .append(hidden("focus", p.id())).append(hidden("waypointId", p.id()));
        sb.append("<p class=\"tv-text\">Nom actuel : <strong>").append(Http.esc(displayName(p))).append("</strong></p>");
        sb.append("<label for=\"tv-new-name\">Nouveau nom</label>");
        sb.append("<input id=\"tv-new-name\" class=\"form-control\" type=\"text\" name=\"displayName\" minlength=\"2\" "
                + "maxlength=\"40\" required autocomplete=\"off\" value=\"").append(Http.esc(p.name()))
                .append("\" data-name-taken=\"").append(Http.esc(com.lodygames.rpgquest.panel.json.Json.write(taken)))
                .append("\" data-name-taken-note=\"tv-new-name-taken\" aria-describedby=\"tv-name-help\">");
        sb.append("<p class=\"field-help\" id=\"tv-name-help\">C'est le nom que voient les joueurs : panneaux, menu de "
                + "voyage, messages. 2 à 40 caractères, différent des autres lieux.</p>");
        sb.append("<p class=\"form-text text-warning-emphasis\" id=\"tv-new-name-taken\" role=\"status\" hidden>")
                .append(Icons.icon("warning")).append("<span class=\"name-taken-text\"></span> Choisis un autre nom : "
                        + "deux lieux ne peuvent pas porter le même.</p>");
        sb.append(consent("waypoint.rename", "Je confirme le nouveau nom"));
        sb.append("<p class=\"tv-keep\">").append(Icons.icon("check"))
                .append("Rien d'autre ne change : l'endroit, les découvertes des joueurs et la borne restent les mêmes.</p>");
        sb.append("<div class=\"btnrow\"><button class=\"btn\" type=\"submit\">").append(Icons.icon("save"))
                .append("Enregistrer le nouveau nom</button></div>");
        return sb.append("</form></section>").toString();
    }

