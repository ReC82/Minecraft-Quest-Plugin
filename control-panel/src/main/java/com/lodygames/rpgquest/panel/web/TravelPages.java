    record Place(String id, String name, String world, String biomeKey, String biomeInstance, int x, int y, int z,
                 boolean active, String beaconId, String createdAt, String modelVersion) {
        boolean hasBeacon() {
            return !beaconId.isEmpty();
        }
    }

    record Beacon(String id, String world, int x, int y, int z, boolean active, boolean autoGenerated,
                  String biomeInstance, String placeId, String createdAt) {
    }

    /** Un lieu du Hub encore sans borne, tel que le plugin le rapporte. */
    record Missing(String placeId, String biomeKey, String biomeInstance, int x, int z, int attempts,
                   boolean inProgress, int nearestBeacon, Long nextRetryEpochMs) {
    }

    record Survey(List<Place> places, List<Beacon> beacons, List<Missing> missing, TravelNetworkDiagnostic diag) {
        Place place(String id) {
            return id == null ? null : places.stream().filter(p -> p.id().equalsIgnoreCase(id)).findFirst().orElse(null);
        }

        String hubWorld() {
            return diag.referenceKnown() ? diag.hubWorld() : "";
        }

        Kind kindOf(String world) {
            if (!hubWorld().isEmpty() && hubWorld().equals(world)) {
                return Kind.HUB;
            }
            boolean waystones = diag.waystoneNetworks().stream().anyMatch(w -> w.world().equals(world));
            return waystones || "wild".equalsIgnoreCase(world) ? Kind.WILD : Kind.OTHER;
        }

        List<TravelNetworkDiagnostic.BeaconRow> beaconAnomalies() {
            return diag.available() && diag.referenceKnown() ? diag.anomalies() : List.of();
        }

        boolean generationDisabled() {
            return diag.available() && diag.referenceKnown() && !diag.hubWorld().isEmpty()
                    && !diag.hubBeaconGenerationEnabled();
        }

        /** Ce que l'onglet « À vérifier » demande de regarder. Les Waystones non découvertes n'en font pas partie. */
        int toCheck() {
            return missing.size() + beaconAnomalies().size() + (generationDisabled() ? 1 : 0);
        }

        String placeName(String id) {
            Place p = place(id);
            return p == null || p.name().isBlank() ? "" : p.name();
        }
    }

