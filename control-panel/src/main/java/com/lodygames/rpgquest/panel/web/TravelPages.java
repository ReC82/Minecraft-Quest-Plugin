    /** Biome lisible ; un biome inconnu (moddé, nouvelle version) reste lisible, jamais vide. */
    static String biomeName(String biomeKey) {
        String key = biomeKey == null ? "" : biomeKey.trim().toLowerCase(Locale.ROOT);
        key = key.contains(":") ? key.substring(key.lastIndexOf(':') + 1) : key;
        String known = BIOMES.get(key);
        return known != null ? known : MiniText.prettifyId(key);
    }

    private static String displayName(Place p) {
        return p.name().isBlank() ? MiniText.prettifyId(p.id()) : p.name();
    }

    /** Comparaison « casse et accents ignorés », comme l'unicité côté plugin. */
    static String fold(String s) {
        String n = Normalizer.normalize(s == null ? "" : s, Normalizer.Form.NFD).replaceAll("\\p{M}", "");
        return n.toLowerCase(Locale.ROOT).replaceAll("\\s+", " ").trim();
    }

    /**
     * Refus avant la file d'un nom déjà porté par un autre lieu, ou inchangé. Le plugin reste seul
     * juge (il revérifie sur l'état réel) ; ceci évite seulement un aller-retour pour rien.
     *
     * @return le message à afficher, ou {@code null} si le nom peut être envoyé
     */
    static String renameConflict(Survey s, String placeId, String newName) {
        Place self = s.place(placeId);
        String wanted = fold(newName);
        if (self != null && fold(self.name()).equals(wanted)) {
            return "« " + newName.trim() + " » est déjà le nom de ce lieu : rien n'a été envoyé.";
        }
        for (Place p : s.places()) {
            if (!p.id().equalsIgnoreCase(placeId) && fold(p.name()).equals(wanted)) {
                return "Le nom « " + newName.trim() + " » est déjà pris par un autre lieu ("
                        + worldName(p.world()) + ") : choisis-en un autre. Rien n'a été envoyé.";
            }
        }
        return null;
    }

